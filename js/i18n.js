  // Sprache: ?lang=en in der URL hat Vorrang, sonst gemerkte Wahl, sonst Deutsch.
  function initialLang() {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "de" || q === "en") return q;
    try { const s = localStorage.getItem("cockpit.lang"); if (s === "de" || s === "en") return s; } catch (e) { /* ignorieren */ }
    return "de";
  }

  let lang = initialLang();
  const listeners = [];

  function tIn(l, key, vars) {
    let s = (DICT[l] && DICT[l][key]) ?? DICT.de[key] ?? key;
    if (vars) for (const k in vars) {
      let v = vars[k];
      if (typeof v === "string" && /^\d{4}-\d{2}-\d{2}$/.test(v)) v = v.split("-").reverse().join("."); // ISO → tt.mm.jjjj
      s = s.replaceAll(`{${k}}`, v);
    }
    return s;
  }

  // Name eines Fachobjekts: DE nur deutsch, EN «English (Deutsch)».
  const t = (key, vars) => tIn(lang, key, vars);
  const term = (de, en) => (lang === "en" && en ? `${en} (${de})` : de);

  function setLang(l) {
    lang = l;
    try { localStorage.setItem("cockpit.lang", l); } catch (e) { /* ignorieren */ }
    document.documentElement.lang = l;
    listeners.forEach((fn) => fn(l));
  }

  window.Cockpit = window.Cockpit || {};
  window.Cockpit.i18n = { t, tIn, term, setLang, getLang: () => lang, onChange: (fn) => listeners.push(fn) };
